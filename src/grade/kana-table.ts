const SMALL = new Set(["ぁ", "ぃ", "ぅ", "ぇ", "ぉ", "ゃ", "ゅ", "ょ", "ゎ"]);
export const isSmallKana = (c: string) => SMALL.has(c);

// 표시는 원래 글자 그대로, 비교는 가타카나를 히라가나로 맞춘 글자로 한다(TalkBuddy pronounce.ts 에서 가져옴).
export const toHiragana = (s: string) => s.replace(/[ァ-ヶ]/g, (k) => String.fromCharCode(k.charCodeAt(0) - 0x60));
export const toKatakana = (s: string) => s.replace(/[ぁ-ゖ]/g, (k) => String.fromCharCode(k.charCodeAt(0) + 0x60));
export const isKatakana = (c: string) => /[ァ-ヺー]/.test(c);
